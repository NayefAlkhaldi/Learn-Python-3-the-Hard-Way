# First, let's make a list.
years = []

# Then, for-loop to append list with years
for i in range(2010):
    # The starting value is 0. So add 1.
	years.append(i+1)

# When we try to access element 2010. We use 2009 because values starts at 0.
print(years[2009])
# output: 2010
# And that's how it works.

# Done!